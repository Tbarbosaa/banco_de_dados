CREATE DATABASE IF NOT EXISTS BD_OFICINA;
USE BD_OFICINA;

CREATE TABLE IF NOT EXISTS CLIENTES (
	CLI_ID INT PRIMARY KEY AUTO_INCREMENT,
    NOME VARCHAR (100) NOT NULL,
    CPF VARCHAR(11) NOT NULL UNIQUE,
    TELEFONE VARCHAR (20),
    EMAIL VARCHAR (100),
    CREATED_AT TIMESTAMP,
    UPDATED_AT TIMESTAMP
);

CREATE TABLE IF NOT EXISTS VEICULOS (
	VEI_ID INT PRIMARY KEY AUTO_INCREMENT,
    PLACA VARCHAR (100) NOT NULL,
    MARCA VARCHAR (50) NOT NULL,
    MODELO VARCHAR (50),
    CLIENTE_ID INT NOT NULL,
    CREATED_AT TIMESTAMP,
    UPDATED_AT TIMESTAMP,
    FOREIGN KEY (CLIENTE_ID) REFERENCES CLIENTES (CLI_ID)
);

CREATE TABLE IF NOT EXISTS AGENDAMENTOS (
	AGE_ID INT PRIMARY KEY AUTO_INCREMENT,
    DATA DATE NOT NULL,
    HORA TIME NOT NULL,
    DESCRICAO VARCHAR (255),
	CREATED_AT TIMESTAMP,
    UPDATED_AT TIMESTAMP,
    VEICULO_ID INT NOT NULL,
    FOREIGN KEY (VEICULO_ID) REFERENCES VEICULOS (VEI_ID)
);

