/* Quantos carros cada cliente tem?*/

SELECT	NOME AS "CLIENTE",
		CPF AS "CPF",
		EMAIL AS "EMAIL",
        COUNT(CLIENTE_ID) AS "QUANTIDADE"
FROM CLIENTES C
LEFT JOIN VEICULOS V ON (V.CLIENTE_ID = C.CLI_ID)
GROUP BY CLI_ID;

/* Quantos agendamentos cada veículos tem?*/

SELECT	MARCA,
		PLACA,
        MODELO,
        COUNT(VEICULO_ID) AS "QUANTIDADE DE AGENDAMENTOS"
FROM VEICULOS V
LEFT JOIN AGENDAMENTOS A ON (A.VEICULO_ID = V.VEI_ID)
GROUP BY VEI_ID;

